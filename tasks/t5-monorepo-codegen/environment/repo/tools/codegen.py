import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "packages" / "shared" / "types.py"


def render(schema):
    lines = ["@dataclass", f"class {schema['name']}:"]
    for f in schema["fields"]:
        lines.append(f"    {f['name']}: {f['type']}")
    return "\n".join(lines)


def main():
    schemas = [json.loads(p.read_text()) for p in sorted((ROOT / "schema").glob("*.json"))]
    body = "\n\n\n".join(render(s) for s in schemas)
    text = "# generated by tools/codegen.py, do not edit\nfrom dataclasses import dataclass\n\n\n" + body + "\n"
    OUT.write_text(text)
    print("codegen: wrote packages/shared/types.py")


if __name__ == "__main__":
    sys.exit(main())
